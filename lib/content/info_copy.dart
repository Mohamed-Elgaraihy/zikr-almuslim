class InfoBlock {
  const InfoBlock(this.body, {this.heading});

  final String? heading;
  final String body;
}

enum InfoKind { about, developer, privacy, terms }

extension InfoKindContent on InfoKind {
  String get title {
    return switch (this) {
      InfoKind.about => 'عن التطبيق',
      InfoKind.developer => 'من نحن',
      InfoKind.privacy => 'سياسة الخصوصية',
      InfoKind.terms => 'شروط الاستخدام',
    };
  }

  List<InfoBlock> get blocks {
    return switch (this) {
      InfoKind.about => aboutBlocks,
      InfoKind.developer => developerBlocks,
      InfoKind.privacy => privacyBlocks,
      InfoKind.terms => termsBlocks,
    };
  }

  bool get showsWebsite => this == InfoKind.developer || this == InfoKind.about;
}

